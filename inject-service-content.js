'use strict';
// inject-service-content.js
// Reads service page drafts from pipeline and writes lib/service-content.js

const fs   = require('fs');
const path = require('path');

const DRAFTS_DIR = 'C:\\Users\\KillerGrowth\\.openclaw\\workspace\\tools\\hyperlocal-pipeline\\drafts\\blogs';

// Map: draft slug → service page slug in the site
const SERVICE_MAP = {
  'shaws-service-general-pest-control': 'pestcontrol',
  'shaws-service-termite-control':      'termites',
  'shaws-service-mosquito-control':     'mosquito-control',
  'shaws-service-spider-control':       'pest-control-spiders',
  'shaws-service-ant-control':          'pest-control-ants',
  'shaws-service-roach-control':        'pest-control-roaches',
  'shaws-service-bed-bug-control':      'pest-control-bedbugs',
};

function mdToHtml(md) {
  const lines = md.split('\n');
  const out = [];
  let inList = false, inParagraph = false;

  function closeParagraph() { if (inParagraph) { out.push('</p>'); inParagraph = false; } }
  function closeList()      { if (inList)      { out.push('</ul>'); inList = false; } }

  for (const line of lines) {
    if (!line.trim()) { closeParagraph(); closeList(); continue; }
    if (/^# /.test(line))   { closeParagraph(); closeList(); out.push(`<h1>${inline(line.slice(2))}</h1>`); continue; }
    if (/^## /.test(line))  { closeParagraph(); closeList(); out.push(`<h2>${inline(line.slice(3))}</h2>`); continue; }
    if (/^### /.test(line)) { closeParagraph(); closeList(); out.push(`<h3>${inline(line.slice(4))}</h3>`); continue; }
    if (/^[-*] /.test(line)) {
      closeParagraph();
      if (!inList) { out.push('<ul>'); inList = true; }
      out.push(`<li>${inline(line.slice(2))}</li>`); continue;
    }
    if (/^\d+\. /.test(line)) {
      closeParagraph(); closeList();
      out.push(`<li>${inline(line.replace(/^\d+\. /,''))}</li>`); continue;
    }
    closeList();
    if (!inParagraph) { out.push('<p>'); inParagraph = true; } else out.push('<br>');
    out.push(inline(line));
  }
  closeParagraph(); closeList();
  return out.join('\n');
}

function inline(text) {
  return text
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\*([^*]+)\*/g,     '<em>$1</em>')
    .replace(/`([^`]+)`/g,       '<code>$1</code>')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>')
    .replace(/—/g, '&mdash;').replace(/–/g, '&ndash;');
}

function parseDraft(draftSlug) {
  const file = path.join(DRAFTS_DIR, `${draftSlug}-blog.md`);
  if (!fs.existsSync(file)) { console.warn(`  ⚠️  Missing: ${draftSlug}-blog.md`); return null; }

  let raw = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');

  // Extract title + metaDesc from second frontmatter block
  let title = '', metaDesc = '';
  const metaMatch = raw.match(/---\nTITLE TAG:([^\n]+)\nMETA DESCRIPTION:([^\n]+)/);
  if (metaMatch) { title = metaMatch[1].trim(); metaDesc = metaMatch[2].trim(); }

  // Extract FAQs
  const faqs = [];
  const faqSection = raw.match(/## Frequently Asked Questions([\s\S]*?)(?=\n## |\n# |$)/i);
  if (faqSection) {
    const qMatches = [...faqSection[1].matchAll(/### (.+)\n\n([\s\S]*?)(?=\n### |\n## |$)/g)];
    for (const m of qMatches) {
      const q = m[1].trim();
      const a = m[2].trim().replace(/\*\*([^*]+)\*\*/g,'$1').replace(/\[([^\]]+)\]\([^)]+\)/g,'$1').replace(/\n/g,' ').slice(0, 500);
      if (q && a) faqs.push({ q, a });
    }
  }

  // Strip both frontmatter blocks
  let md = raw.replace(/^---\n[\s\S]*?\n---\n*/,'').replace(/^---\n[\s\S]*?\n---\n*/,'').trim();
  // Fix common mojibake
  md = md.replace(/\uFFFD\uFFFD\uFFFD/g,'—').replace(/â€"/g,'—').replace(/â€™/g,"'");

  const html = mdToHtml(md);
  return { title, metaDesc, html, faqs };
}

const output = {};
for (const [draftSlug, serviceSlug] of Object.entries(SERVICE_MAP)) {
  const parsed = parseDraft(draftSlug);
  if (parsed) {
    output[serviceSlug] = parsed;
    console.log(`  ✅ ${serviceSlug} — ${parsed.faqs.length} FAQs, ${parsed.html.length} chars`);
  }
}

const js = `'use strict';
// AUTO-GENERATED by inject-service-content.js — do not edit manually
module.exports = ${JSON.stringify(output, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, 'lib', 'service-content.js'), js, 'utf8');
console.log('\n✅ lib/service-content.js written.');
